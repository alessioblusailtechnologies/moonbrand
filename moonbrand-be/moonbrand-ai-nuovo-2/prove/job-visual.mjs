import pg from 'pg';
const url = process.env.DATABASE_URL ?? '';
const local = url.includes('localhost') || url.includes('127.0.0.1');
const pool = new pg.Pool({ connectionString: url, ...(local ? {} : { ssl: { rejectUnauthorized: false } }) });
const id = process.argv[2];
const { rows } = await pool.query(`select * from presenza.ai_jobs where id = $1`, [id]);
const job = rows[0];
console.log('colonne:', Object.keys(job).join(', '));
console.log('brand:', job.input.brandId, '| canali:', JSON.stringify(job.input.brand?.channels), '| nome:', job.input.brand?.identity?.name, '| lingua:', job.input.brand?.identity?.language, '| template:', job.input.brand?.template);
console.log('palette:', JSON.stringify(job.input.brand?.palette), '| fonts:', JSON.stringify(job.input.brand?.fonts));
console.log('result:', JSON.stringify(job.result).slice(0, 1500));
for (const key of ['steps', 'log', 'session_id', 'cost_usd', 'error', 'started_at', 'finished_at']) if (key in job) console.log(key + ':', typeof job[key] === 'object' ? JSON.stringify(job[key]).slice(0, 3000) : job[key]);
const usage = await pool.query(`select * from presenza.ai_usage where job_id = $1 order by created_at`, [id]).catch((e) => ({ rows: [], error: e.message }));
console.log('usage:', usage.error ?? usage.rows.map((r) => [r.task, r.model, r.units, r.unit, r.cost_usd, r.seconds ?? r.duration_ms].join(' ')).join('\n'));
await pool.end();
